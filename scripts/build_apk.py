#!/usr/bin/env python3
"""Build a signed DevvioRD APK without Gradle.

Pipeline (the same steps Gradle performs, driven explicitly so the build needs
no internet access):
    aapt2 compile  ->  aapt2 link (+ R.java)  ->  ECJ (Java 8 bytecode)
    -> D8 (dex)  ->  zip (aligned)  ->  apksigner (v1/v2/v3)  ->  verify

Usage:
    python3 scripts/build_apk.py [--debug] [--toolchain DIR] [--out DIR]

Requirements (checked at startup): toolchain/tools/{aapt2,android.jar,ecj.jar,
d8.jar,apksigner.jar} and toolchain/jdk/bin/java.
"""
import argparse
import hashlib
import os
import re
import shutil
import subprocess
import sys
import time
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP = os.path.join(ROOT, "app")
BUILD = os.path.join(ROOT, "build-tmp")
OUT = os.path.join(ROOT, "dist")

VERSION_NAME = "1.0.0"
VERSION_CODE = 1
MIN_SDK = 21
TARGET_SDK = 34
PACKAGE = "ai.devvio.rd"


def log(msg):
    print(f"[build] {msg}", flush=True)


def run(cmd, cwd=None, quiet=False):
    if not quiet:
        log("$ " + " ".join(os.path.basename(c) if i == 0 else c for i, c in enumerate(cmd)))
    p = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if p.returncode != 0:
        sys.stderr.write(p.stdout)
        sys.stderr.write(p.stderr)
        raise SystemExit(f"command failed ({p.returncode}): {' '.join(cmd[:3])}...")
    return p.stdout + p.stderr


def require(path, what):
    if not os.path.exists(path):
        raise SystemExit(f"missing {what}: {path}\nRun scripts/fetch_toolchain.sh first.")
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--toolchain", default=os.path.join(ROOT, "toolchain"))
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--debug", action="store_true", help="debug build (no version bump)")
    args = ap.parse_args()

    T = args.toolchain
    java = require(os.path.join(T, "jdk", "bin", "java"), "JDK")
    aapt2 = require(os.path.join(T, "tools", "aapt2"), "aapt2")
    android_jar = require(os.path.join(T, "tools", "android.jar"), "android.jar")
    ecj = require(os.path.join(T, "tools", "ecj.jar"), "ecj.jar")
    d8 = require(os.path.join(T, "tools", "d8.jar"), "d8.jar")
    apksigner = require(os.path.join(T, "tools", "apksigner.jar"), "apksigner.jar")
    keystore = os.path.join(APP, "devviord-release.jks")
    if not os.path.exists(keystore):
        keystore = os.path.join(T, "tools", "debug.keystore")
        ks_pass, key_alias = "android", "androiddebugkey"
    else:
        ks_pass, key_alias = "devviord", "devviord"

    work = BUILD
    if os.path.exists(work):
        shutil.rmtree(work)
    for d in ("res-compiled", "gen", "classes", "dex", "apk"):
        os.makedirs(os.path.join(work, d), exist_ok=True)

    t0 = time.time()

    # ---------------------------------------------------------------- sources
    java_files = []
    for base, _, files in os.walk(os.path.join(APP, "src")):
        for f in files:
            if f.endswith(".java"):
                java_files.append(os.path.join(base, f))
    if not java_files:
        raise SystemExit("no Java sources found")
    log(f"{len(java_files)} Java sources")

    # ---------------------------------------------------------------- BuildConfig
    build_config = os.path.join(work, "gen", PACKAGE.replace(".", "/"), "BuildConfig.java")
    os.makedirs(os.path.dirname(build_config), exist_ok=True)
    with open(build_config, "w") as f:
        f.write(f"""package {PACKAGE};

/** Generated by scripts/build_apk.py - do not edit. */
public final class BuildConfig {{
    public static final boolean DEBUG = {str(args.debug).lower()};
    public static final String APPLICATION_ID = "{PACKAGE}";
    public static final String BUILD_TYPE = "{'debug' if args.debug else 'release'}";
    public static final int VERSION_CODE = {VERSION_CODE};
    public static final String VERSION_NAME = "{VERSION_NAME}";
}}
""")

    # ---------------------------------------------------------------- resources
    compiled_res = os.path.join(work, "res-compiled", "res.zip")
    run([aapt2, "compile", "--dir", os.path.join(APP, "res"), "-o", compiled_res])
    base_apk = os.path.join(work, "apk", "base.apk")
    r_java_dir = os.path.join(work, "gen")
    run([aapt2, "link",
         "-o", base_apk,
         "--manifest", os.path.join(APP, "AndroidManifest.xml"),
         "-I", android_jar,
         "--java", r_java_dir,
         "--min-sdk-version", str(MIN_SDK),
         "--target-sdk-version", str(TARGET_SDK),
         "--version-code", str(VERSION_CODE),
         "--version-name", VERSION_NAME,
         "--auto-add-overlay",
         compiled_res])
    r_java = os.path.join(r_java_dir, *PACKAGE.split("."), "R.java")
    require(r_java, "generated R.java")
    log("resources compiled and linked")

    # ---------------------------------------------------------------- compile
    classes_dir = os.path.join(work, "classes")
    srcs = java_files + [r_java, build_config]
    run([java, "-jar", ecj,
         "-source", "8", "-target", "8",
         "-proc:none", "-nowarn", "-g",
         "-encoding", "UTF-8",
         "-cp", android_jar,
         "-d", classes_dir] + srcs)
    class_files = []
    for base, _, files in os.walk(classes_dir):
        for f in files:
            if f.endswith(".class"):
                class_files.append(os.path.join(base, f))
    if not class_files:
        raise SystemExit("compilation produced no classes")
    log(f"compiled {len(class_files)} classes")

    # ---------------------------------------------------------------- dex
    dex_dir = os.path.join(work, "dex")
    run([java, "-cp", d8, "com.android.tools.r8.D8",
         "--min-api", str(MIN_SDK),
         "--lib", android_jar,
         "--release",
         "--output", dex_dir] + class_files)
    dex = os.path.join(dex_dir, "classes.dex")
    require(dex, "classes.dex")
    log(f"dexed ({os.path.getsize(dex) // 1024} KiB)")

    # ---------------------------------------------------------------- package
    unsigned = os.path.join(work, "apk", "unsigned.apk")
    with zipfile.ZipFile(base_apk, "r") as src:
        entries = [(i, src.read(i.filename)) for i in src.infolist()]
    # resources.arsc must be STORED and 4-byte aligned for targetSdk >= 30.
    with zipfile.ZipFile(unsigned, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for info, data in entries:
            name = info.filename
            if name in ("resources.arsc",) or info.compress_type == zipfile.ZIP_STORED:
                zi = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 1, 1, 0))
                zi.compress_type = zipfile.ZIP_STORED
                zi.external_attr = info.external_attr
                # pad so the payload starts on a 4-byte boundary
                zi.extra = b""
                z.writestr(zi, data)
            else:
                zi = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 1, 1, 0))
                zi.compress_type = zipfile.ZIP_DEFLATED
                zi.external_attr = info.external_attr
                z.writestr(zi, data)
        zi = zipfile.ZipInfo("classes.dex", date_time=(1980, 1, 1, 1, 1, 0))
        zi.compress_type = zipfile.ZIP_DEFLATED
        z.writestr(zi, open(dex, "rb").read())

    # ---------------------------------------------------------------- align
    aligned = os.path.join(work, "apk", "aligned.apk")
    zipalign_py(unsigned, aligned, 4)

    # ---------------------------------------------------------------- sign
    signed = os.path.join(work, "apk", f"DevvioRD-{VERSION_NAME}.apk")
    run([java, "-jar", apksigner, "sign",
         "--ks", keystore,
         "--ks-pass", f"pass:{ks_pass}",
         "--key-pass", f"pass:{ks_pass}",
         "--ks-key-alias", key_alias,
         "--v1-signing-enabled", "true",
         "--v2-signing-enabled", "true",
         "--v3-signing-enabled", "true",
         "--min-sdk-version", str(MIN_SDK),
         "--out", signed, aligned], quiet=False)
    verify_out = run([java, "-jar", apksigner, "verify", "--verbose", "--print-certs", signed])
    schemes = [s for s in ("v1", "v2", "v3") if re.search(rf"Verified using {s} scheme.*true", verify_out)]
    if not schemes:
        raise SystemExit("signature verification did not report any scheme\n" + verify_out)
    log("signature verified: " + ", ".join(schemes))

    # ---------------------------------------------------------------- copy out
    os.makedirs(args.out, exist_ok=True)
    final = os.path.join(args.out, os.path.basename(signed))
    shutil.copy2(signed, final)
    size = os.path.getsize(final)
    digest = hashlib.sha256(open(final, "rb").read()).hexdigest()

    # badging for the record
    badging = subprocess.run([aapt2, "dump", "badging", final], capture_output=True, text=True).stdout
    pkg_line = next((l for l in badging.splitlines() if l.startswith("package:")), "")
    sdk_line = next((l for l in badging.splitlines() if l.startswith("sdkVersion")), "")
    tgt_line = next((l for l in badging.splitlines() if l.startswith("targetSdkVersion")), "")

    log("done in %.1fs" % (time.time() - t0))
    print()
    print("APK      :", final)
    print("size     : %.2f MB (%d bytes)" % (size / (1024 * 1024), size))
    print("sha256   :", digest)
    print("package  :", pkg_line)
    print("min/target:", sdk_line, "|", tgt_line)
    print("schemes  :", ",".join(schemes))
    with open(final + ".sha256", "w") as f:
        f.write(digest + "  " + os.path.basename(final) + "\n")
    return 0


def zipalign_py(src, dst, align=4):
    """Rewrite the zip so every STORED entry starts on an `align` boundary.

    Equivalent to `zipalign -p 4` for our purposes: alignment matters for
    uncompressed entries (resources.arsc, .so files) that are mmapped on device.
    """
    with zipfile.ZipFile(src, "r") as zin:
        infos = zin.infolist()
        data = [(i, zin.read(i.filename)) for i in infos]
    with zipfile.ZipFile(dst, "w") as zout:
        for info, blob in data:
            zi = zipfile.ZipInfo(info.filename, date_time=info.date_time)
            zi.compress_type = info.compress_type
            zi.external_attr = info.external_attr
            zi.create_system = 0
            if info.compress_type == zipfile.ZIP_STORED:
                # Compute padding: local header is 30 bytes + name + extra.
                offset = zout.fp.tell()
                local_extra = len(info.filename) + 30
                pad = (align - ((offset + local_extra) % align)) % align
                zi.extra = b"\x00" * pad
            zout.writestr(zi, blob)
    return dst


if __name__ == "__main__":
    sys.exit(main())
